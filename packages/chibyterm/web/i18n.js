  function normalize(raw) {
    var v = String(raw || '').trim().replace(/_/g, '-');
    var low = v.toLowerCase();
    if (low === 'zh-tw' || low === 'zh-hant' || low === 'zh-hk' || low === 'tw') return 'zh-TW';
    if (low === 'en' || low.indexOf('en-') === 0) return 'en';
    if (low === 'zh-cn' || low === 'zh' || low === 'zh-hans' || low === 'cn') return 'zh-CN';
    if (SUPPORTED.indexOf(v) >= 0) return v;
    return 'zh-CN';
  }

  function load() {
    try {
      return normalize(localStorage.getItem(STORAGE_KEY) || 'zh-CN');
    } catch (_) {
      return 'zh-CN';
    }
  }

  function save(locale) {
    var loc = normalize(locale);
    try {
      localStorage.setItem(STORAGE_KEY, loc);
    } catch (_) {}
    return loc;
  }

  function t(key, vars) {
    var loc = I18n.locale || load();
    var bag = STR[loc] || STR['zh-CN'];
    var s = bag[key] != null ? bag[key] : (STR['zh-CN'][key] || key);
    if (vars && typeof vars === 'object') {
      Object.keys(vars).forEach(function (k) {
        s = String(s).split('{' + k + '}').join(String(vars[k]));
      });
    }
    return s;
  }

  var I18n = {
    STORAGE_KEY: STORAGE_KEY,
    SUPPORTED: SUPPORTED,
    locale: load(),
    normalize: normalize,
    load: load,
    save: save,
    t: t,
    setLocale: function (locale) {
      I18n.locale = save(locale);
      try {
        document.documentElement.setAttribute('lang', I18n.locale === 'en' ? 'en' : 'zh');
        document.title = t('docTitle');
      } catch (_) {}
      return I18n.locale;
    },
  };

  I18n.setLocale(I18n.locale);
  global.ChibyI18n = I18n;
